import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";

export async function checkNormalCustomerFlow({ page, browser, baseUrl, fixture, pool, artifacts }) {
  const { workorderId, companyId, locationId } = fixture;
  await page.goto(`${baseUrl}/?workorder=${workorderId}&section=chat`);
  await page.getByRole("tab", { name: "Customer", exact: true }).click();
  await page.getByRole("button", { name: "Prepare Estimate", exact: true }).click();
  await page.getByRole("button", { name: "Review Estimate", exact: true }).click();
  await page.getByRole("button", { name: "Issue Estimate", exact: true }).waitFor();
  assert.ok((await page.getByRole("region", { name: "Document preview", exact: true }).innerText()).includes("$300.00"));
  const issueResponse = page.waitForResponse(response => new URL(response.url()).pathname === "/api/customer-documents/revisions" && response.request().method() === "POST");
  await page.getByRole("button", { name: "Issue Estimate", exact: true }).click();
  const response = await issueResponse;
  const issueBody = response.request().postDataJSON();
  assert.equal(response.status(), 201, await response.text());
  const issued = await response.json();
  assert.equal(issueBody.draftId, null);
  assert.equal(issueBody.predecessorRevisionId, null);
  await page.getByText("Awaiting approval", { exact: true }).waitFor();
  const replay = await page.request.post(`${baseUrl}/api/customer-documents/revisions`, { data: issueBody });
  assert.equal(replay.status(), 201, await replay.text());
  assert.equal((await replay.json()).revision.id, issued.revision.id, "First issue is retry-safe");
  const duplicate = await page.request.post(`${baseUrl}/api/customer-documents/revisions`, { data: { ...issueBody, idempotencyKey: randomUUID() } });
  assert.equal(duplicate.status(), 409, "A competing first issue cannot create a second document");
  const invalid = await page.request.post(`${baseUrl}/api/customer-documents/revisions`, { data: { ...issueBody, documentId: issued.revision.documentId, idempotencyKey: randomUUID() } });
  assert.equal(invalid.status(), 400, "Partial revision lineage is rejected");
  const foreign = await page.request.post(`${baseUrl}/api/customer-documents/previews`, { data: { companyId: randomUUID(), locationId, source: issueBody.source, documentType: "estimate", adjustments: {} } });
  assert.ok([403, 404].includes(foreign.status()), "Preview cannot cross company scope");
  const stale = await page.request.post(`${baseUrl}/api/customer-documents/previews`, { data: { companyId, locationId, source: { ...issueBody.source, expectedVersion: issueBody.source.expectedVersion + 1 }, documentType: "estimate", adjustments: {} } });
  assert.equal(stale.status(), 409, "Stale Workorder source cannot be previewed");
  const original = (await pool.query("select snapshot from customer_document_revisions where id=$1", [issued.revision.id])).rows[0].snapshot;
  const linkResponse = page.waitForResponse(response => new URL(response.url()).pathname === `/api/customer-repair/workorders/${workorderId}/links` && response.request().method() === "POST");
  await page.getByRole("button", { name: "Customer link", exact: true }).click();
  const link = await (await linkResponse).json();
  const openCustomer = page.getByRole("link", { name: "Open customer view", exact: true });
  await openCustomer.waitFor();
  const href = await openCustomer.getAttribute("href");
  const customerContext = await browser.newContext({ viewport: { width: 390, height: 844 } });
  try {
    const customer = await customerContext.newPage();
    customer.setDefaultTimeout(12000);
    await customer.goto(href);
    await customer.getByRole("button", { name: "View estimate", exact: true }).click();
    await customer.getByRole("button", { name: "Approve estimate", exact: true }).click();
    await customer.getByRole("region", { name: "Estimate response", exact: true }).getByLabel("Your name", { exact: true }).fill("Local Test Customer");
    await customer.getByRole("button", { name: "Confirm response", exact: true }).click();
    await customer.getByText("Estimate approved", { exact: true }).waitFor();
    await customer.screenshot({ path: `${artifacts}/customer-approved.png`, fullPage: true });
    await page.getByRole("tab", { name: "Chat", exact: true }).click();
    await page.getByRole("tab", { name: "Customer", exact: true }).click();
    const staffMessage = page.getByRole("textbox", { name: "Message to customer", exact: true });
    const staffLog = page.getByRole("region", { name: "Customer chat", exact: true }).getByRole("log");
    const customerLog = customer.getByRole("region", { name: "Chat with the shop", exact: true }).getByRole("log");
    await staffMessage.fill("Shop: your Estimate is ready and approved.");
    await page.getByRole("button", { name: "Send to customer", exact: true }).click();
    await staffLog.getByText("Shop: your Estimate is ready and approved.", { exact: true }).waitFor();
    await customer.getByRole("navigation", { name: "Repair navigation", exact: true }).getByRole("button", { name: "Chat", exact: true }).click();
    await customerLog.getByText("Shop: your Estimate is ready and approved.", { exact: true }).waitFor();
    assert.equal(await customer.getByText("Private shop note for normal-flow regression", { exact: true }).count(), 0, "Internal chat never reaches customer");
    await customer.getByRole("region", { name: "Chat with the shop", exact: true }).getByLabel("Your name", { exact: true }).fill("Local Test Customer");
    await customer.getByRole("textbox", { name: "Message to shop", exact: true }).fill("Customer: approved, please proceed.");
    await customer.getByRole("button", { name: "Send message to shop", exact: true }).click();
    await customerLog.getByText("Customer: approved, please proceed.", { exact: true }).waitFor();
    await page.getByRole("region", { name: "Customer chat", exact: true }).getByRole("button", { name: "Refresh", exact: true }).click();
    await staffLog.getByText("Customer: approved, please proceed.", { exact: true }).waitFor();
    await page.screenshot({ path: `${artifacts}/staff-customer-chat.png`, fullPage: true });
    await page.getByRole("tab", { name: "Documents", exact: true }).click();
    await page.getByRole("button", { name: "More document options", exact: true }).click();
    await page.getByRole("menuitem", { name: "Refresh", exact: true }).click();
    await page.getByText("Accepted", { exact: true }).waitFor();
    await page.getByRole("button", { name: "More document options", exact: true }).click();
    await page.getByRole("menuitem", { name: "Update estimate", exact: true }).click();
    await page.getByRole("button", { name: "Review revised Estimate", exact: true }).click();
    await page.getByRole("button", { name: "Issue revised Estimate", exact: true }).click();
    await page.getByRole("heading", { name: /R2$/ }).waitFor();
    const rows = (await pool.query("select r.revision_number,r.predecessor_revision_id,r.snapshot,d.draft_id from customer_document_revisions r join customer_documents d on d.id=r.document_id where d.company_id=$1 and d.location_id=$2 and d.workorder_id=$3 order by r.revision_number", [companyId, locationId, workorderId])).rows;
    assert.equal(rows.length, 2);
    assert.equal(rows[1].predecessor_revision_id, issued.revision.id);
    assert.equal(rows[1].draft_id, null);
    assert.deepEqual(rows[0].snapshot, original, "Issuing a revision never rewrites the accepted snapshot");
    const oldApproval = await customer.request.post(`${baseUrl}/api/customer-repair/portal/responses`, { headers: { "x-customer-repair-grant": link.rawToken }, data: { revisionId: issued.revision.id, response: "accepted", customerName: "Local Test Customer", idempotencyKey: randomUUID() } });
    assert.equal(oldApproval.status(), 409, "Superseded Estimate cannot receive a new approval");
    await page.reload();
    await page.getByRole("tab", { name: "Documents", exact: true }).click();
    await page.getByRole("heading", { name: /R2$/ }).waitFor();
    await customer.reload();
    await customerLog.getByText("Customer: approved, please proceed.", { exact: true }).waitFor();
    const revoked = await page.request.post(`${baseUrl}/api/customer-repair/links/${link.grant.id}/revoke`, { data: { companyId, locationId, workorderId } });
    assert.equal(revoked.status(), 200);
    const denied = await customer.request.get(`${baseUrl}/api/customer-repair/portal`, { headers: { "x-customer-repair-grant": link.rawToken } });
    assert.equal(denied.status(), 404, "Revoked customer link loses access");
  } finally { await customerContext.close(); }
}
